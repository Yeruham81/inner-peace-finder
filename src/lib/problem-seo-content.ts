const CANONICAL_SLUGS = new Set<string>(CANONICAL_PROBLEM_SLUGS);

export function hasCompleteProblemSeoContent(content: ProblemSeoContent): boolean {
  return (
    CANONICAL_SLUGS.has(content.slug) &&
    content.seoTitle.trim().length >= 25 &&
    content.seoTitle.trim().length <= 70 &&
    content.metaDescription.trim().length >= 100 &&
    content.metaDescription.trim().length <= 180 &&
    content.summary.trim().length >= 70 &&
    content.intro.trim().length >= 180 &&
    content.commonSituations.length >= 3 &&
    content.matchingGuidance.trim().length >= 120
  );
}

export function getProblemSeoContent(slug: string): ProblemSeoContent | null {
  if (!CANONICAL_SLUGS.has(slug)) return null;
  return PROBLEM_SEO_CONTENT[slug as CanonicalProblemSlug] ?? null;
}

export function getPublishedProblemSeoContent(slug: string): ProblemSeoContent | null {
  const content = getProblemSeoContent(slug);
  if (!content || content.status !== "published" || !hasCompleteProblemSeoContent(content)) {
    return null;
  }
  return content;
}

export function isProblemSeoPublished(slug: string): boolean {
  return getPublishedProblemSeoContent(slug) !== null;
}

export function problemSeoStatus(slug: string): ProblemSeoStatus {
  return getPublishedProblemSeoContent(slug) ? "published" : "draft";
}

export function listPublishedProblemSeoContent(): ProblemSeoContent[] {
  return Object.values(PROBLEM_SEO_CONTENT)
    .filter((content): content is ProblemSeoContent => {
      if (!content) return false;
      return content.status === "published" && hasCompleteProblemSeoContent(content);
    })
    .sort((a, b) => a.sortOrder - b.sortOrder);
}
